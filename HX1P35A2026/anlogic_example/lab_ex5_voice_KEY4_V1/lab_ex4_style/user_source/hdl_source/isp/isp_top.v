function [7:0] meter_gray;
    input [23:0] rgb;
    reg [9:0] v;
    begin v={2'b0,rgb[23:16]}+{1'b0,rgb[15:8],1'b0}+{2'b0,rgb[7:0]};meter_gray=v[9:2];end
endfunction
function [7:0] meter_peak;
    input [23:0] rgb;reg [7:0] rg;
    begin rg=rgb[23:16]>rgb[15:8]?rgb[23:16]:rgb[15:8];
        meter_peak=rg>rgb[7:0]?rg:rgb[7:0];end
endfunction
wire [31:0] pre_samples,awb_samples,awb_peaks;
genvar mi;
generate for(mi=0;mi<4;mi=mi+1) begin: meters
    assign pre_samples[mi*8 +:8]=meter_gray(m_aixs_tdata_96[mi*24 +:24]);
    assign awb_samples[mi*8 +:8]=meter_gray(awb_O_tdata[mi*24 +:24]);
    assign awb_peaks[mi*8 +:8]=meter_peak(awb_O_tdata[mi*24 +:24]);
end endgenerate
