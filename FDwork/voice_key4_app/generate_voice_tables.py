"""Deterministic offline constants and an independent DFT/MFCC self-test vector."""
from pathlib import Path
import math, cmath

N=512; RATE=15625; FRAME=400; DIM=13
window=[.54-.46*math.cos(2*math.pi*i/(FRAME-1)) for i in range(FRAME)]
twiddle=[(math.cos(-2*math.pi*i/N),math.sin(-2*math.pi*i/N)) for i in range(N//2)]
low=2595*math.log10(1+80/700)
high=2595*math.log10(1+7000/700)
bins=[int((N+1)*700*(10**((low+(high-low)*i/27)/2595)-1)/RATE) for i in range(28)]
assert all(a<b for a,b in zip(bins,bins[1:])) and bins[-1]<=256
dct=[[math.sqrt(2/26)*math.cos(math.pi*(k+.5)*(d+1)/26) for k in range(26)] for d in range(DIM)]
tone=[round(10000*math.sin(2*math.pi*997*i/RATE)+3000*math.sin(2*math.pi*2033*i/RATE)) for i in range(FRAME)]
signal=[(tone[i]-(.97*tone[i-1] if i else 0))*window[i]/32768 for i in range(FRAME)]
# Direct DFT is independent of the on-board radix-2 FFT implementation.
spectrum=[sum(x*cmath.exp(-2j*math.pi*k*i/N) for i,x in enumerate(signal)) for k in range(257)]
power=[abs(x)**2 for x in spectrum]
mel=[]
for lo,mid,hi in zip(bins,bins[1:],bins[2:]):
    e=sum(power[j]*(j-lo)/(mid-lo) for j in range(lo,mid))
    e+=sum(power[j]*(hi-j)/(hi-mid) for j in range(mid,hi))
    mel.append(math.log(max(e,1e-9)))
q=lambda x: int(x+.5) if x>=0 else int(x-.5)
expected=[q(64*sum(a*b for a,b in zip(row,mel))) for row in dct]
def floats(seq):
    return ','.join(f'{x:.9e}f' for x in seq)
text='// Generated by generate_voice_tables.py; sample rate 15625 Hz.\n'
text+='static const float voice_window[400]={'+floats(window)+'};\n'
text+='static const float voice_twiddle[256][2]={'+','.join('{'+floats(row)+'}' for row in twiddle)+'};\n'
text+='static const unsigned voice_mel_bins[28]={'+','.join(map(str,bins))+'};\n'
text+='static const float voice_dct[13][26]={'+','.join('{'+floats(row)+'}' for row in dct)+'};\n'
text+='static const int16_t voice_test_tone[400]={'+','.join(map(str,tone))+'};\n'
text+='static const int16_t voice_test_expected[13]={'+','.join(map(str,expected))+'};\n'
Path(__file__).with_name('voice_tables.h').write_text(text,encoding='ascii')
print('MFCC constants generated; DFT self-test expected:',expected)
